// {8'h02, r_rsp[23:0]}: {head,r_rsp}
#define RSP_CONCAT(head, rsp) (((head) << 24) | ((rsp)&0x00ffffff))

void GC0802_change_pll_settings(uint32_t base_addr, uint32_t offset_addr, uint32_t target_settings) {
  uint32_t r_rsp;
  r_rsp = READ_BURST_32(base_addr, offset_addr);
  WRITE_BURST_32(base_addr, offset_addr, RSP_CONCAT(0x2, r_rsp));
  WRITE_BURST_32(base_addr, offset_addr, RSP_CONCAT(0x3, r_rsp));
  WRITE_BURST_32(base_addr, offset_addr, RSP_CONCAT(0x3, target_settings));
  WRITE_BURST_32(base_addr, offset_addr, RSP_CONCAT(0x2, target_settings));
  uint32_t response = READ_BURST_32(base_addr, offset_addr);
  // GC0802_L1_SCHEDULER_BFM_wait_a_bit_change
  while ((response & 0x80000000) != 0x80000000) {
    response = READ_BURST_32(base_addr, offset_addr);
  }
  WRITE_BURST_32(base_addr, offset_addr, RSP_CONCAT(0x00, target_settings));
}

