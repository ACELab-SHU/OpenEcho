double calculateSNR() {
  double noiseEnergy;
  double signalEnergy;
  double sumEnergy;
  double SNR;
  for (int i = 0; i < size_x; i++) {
    sumEnergy += o[i];
  }
  // signalEnergy = o[16] + o[2032];
  // signalEnergy = o[32] + o[2016];
  // signalEnergy = o[9] + o[2040];
  signalEnergy = o[64] + o[1984];
  noiseEnergy  = sumEnergy - signalEnergy;
  SNR          = signalEnergy / noiseEnergy;
  printf("Peak[1]: %d, Peak[2]: %d\n", (int)o[64], (int)o[1984]);
  printf("signal Energy: %d\n", (int)signalEnergy);
  printf("noise Energy: %d\n", (int)noiseEnergy);
  return SNR;
}

