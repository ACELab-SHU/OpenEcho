void changePosition(complexNumber* x) {
  int j = 0, k;
  complexNumber temp;
  for (int i = 0; i < size_x - 1; i++) {
    if (i < j) {
      temp = x[i];
      x[i] = x[j];
      x[j] = temp;
    }
    k = size_x / 2;
    while (j >= k) {
      j = j - k;
      k = k / 2;
    }
    j = j + k;
  }
}

void fastFourierOperation(complexNumber* x) {
  int l = 0;
  complexNumber up, down, product;
  changePosition(x);                              // 偶奇变换算法
  for (int i = 0; i < log(size_x) / log(2); i++)  // 一级蝶形运算
  {
    l = 1 << i;
    for (int j = 0; j < size_x; j += 2 * l)  // 一组蝶形运算
    {
      for (int k = 0; k < l; k++)  // 一个蝶形运算
      {
        mul(x[j + k + l], W[size_x * k / 2 / l], &product);
        add(x[j + k], product, &up);
        sub(x[j + k], product, &down);
        x[j + k]     = up;
        x[j + k + l] = down;
      }
    }
  }
  storeOutputMagnitude(x);
}

